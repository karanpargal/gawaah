// Writes arkiv/evidence.md from a live query: every Gawaah entity on Tiramisu, who created it,
// and the wallet that funded the one-time creators. Re-run right before submitting.
//
//   pnpm evidence
import { writeFileSync } from "node:fs"
import { eq } from "@arkiv-network/sdk/query"
import type { Hex } from "viem"
import { privateKeyToAccount } from "viem/accounts"
import { EXPLORER, publicClient } from "../src/arkiv/client"
import { APP, Attr, BURN_ADDRESS, Kind } from "../src/arkiv/schema"

process.loadEnvFile?.(".env")
const key = process.env.ARKIV_PRIVATE_KEY as Hex | undefined
const funder = key ? privateKeyToAccount(key).address : null

const pub = publicClient()
const kinds: Record<string, number> = {}
const creators = new Set<string>()
const reports: { key: Hex; creator: Hex; block: bigint; sealed: boolean; title: string }[] = []

const q = pub
  .select({ key: true, creator: true, owner: true, createdAt: true, creationFlags: true, attributes: true, payload: true })
  .where(eq(Attr.app, APP))
  .limit(200)

for await (const e of q) {
  const kind = String(e.attributes[Attr.kind]?.value)
  kinds[kind] = (kinds[kind] ?? 0) + 1
  creators.add(e.creator.toLowerCase())
  if (kind !== Kind.Report) continue
  let title = ""
  try {
    title = String(e.toJson().title ?? "")
  } catch {}
  reports.push({
    key: e.key,
    creator: e.creator,
    block: e.createdAt,
    sealed:
      e.creationFlags.readonly &&
      e.creationFlags.permissionlessExtension &&
      e.owner.toLowerCase() === BURN_ADDRESS.toLowerCase(),
    title: title.replace(/\|/g, "/"),
  })
}
reports.sort((a, b) => Number(a.block - b.block))

const out = [
  "# On-chain evidence",
  "",
  `Every Gawaah entity on Tiramisu (chain ID \`7738577\`), generated by \`pnpm evidence\` at ${new Date().toISOString().slice(0, 16).replace("T", " ")} UTC.`,
  "",
  "## Wallets",
  "",
  "By design, every entity is created by a **one-time wallet**. One wallet funded all of them, so its outgoing transfers lead to every creator:",
  "",
  funder ? `- **Funder:** [\`${funder}\`](${EXPLORER}/address/${funder})` : "- Funder: (run with `.env` to include)",
  "",
  `**Totals:** ${Object.entries(kinds).map(([k, n]) => `${n} ${k}`).join(", ")} entities, from ${creators.size} distinct creator wallets.`,
  "",
  "## Reports",
  "",
  "| Report entity | Creator (`$creator`) | Created at block | Sealed | Title |",
  "|---|---|---|---|---|",
  ...reports.map(
    (r) =>
      `| [\`${r.key.slice(0, 10)}…\`](${EXPLORER}/entity/${r.key}) | [\`${r.creator}\`](${EXPLORER}/address/${r.creator}) | ${r.block} | ${r.sealed ? "yes" : "no"} | ${r.title} |`,
  ),
  "",
  "Where reports come from: `[SMOKE TEST]` is `pnpm smoke`, `[E2E TEST]` was posted through the browser, and reports whose text says *Synthetic demo report* come from `pnpm seed`; all of those are synthetic. The rest come from `pnpm seed:news`: summaries of published coverage of the October 2026 Delhi protests, with source links in the payload, no personal names, and freely licensed location photos (credits in `scripts/news-photos/CREDITS.md`).",
  "",
  "## If entities have expired by the time you read this",
  "",
  "That's expected: reports nobody vouches for are meant to vanish. Each creation transaction stays on-chain, so open a creator address above in the explorer to see it. Or re-run `pnpm smoke` with any funded key to reproduce the whole lifecycle.",
  "",
]

writeFileSync("arkiv/evidence.md", out.join("\n"))
console.log(kinds, `${creators.size} creators`, `${reports.length} reports`)
